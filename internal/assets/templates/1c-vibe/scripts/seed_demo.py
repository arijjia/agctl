#!/usr/bin/env python3
"""Создаёт три демо-задачи в тестовом проекте Jira (для прогона MVP).

Использование:
  python3 seed_demo.py PROJECT-KEY          # создать задачи
  python3 seed_demo.py PROJECT-KEY --dry    # показать, что будет создано

Тексты задач — из demo-project/tasks/demo-tasks.md (лежат рядом в данных
скрипта, чтобы не парсить markdown). Тип задачи: Task; если в проекте тип
называется иначе, поменяй ISSUE_TYPE ниже.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from jira_client import api, create_issue

ISSUE_TYPE = "Задача"

DEMO_TASKS = [
    (
        "Функция Приветствие: некорректная работа с пустым наименованием",
        "В модуле объекта справочника Товары функция Приветствие(Товар) при пустом "
        "наименовании товара возвращает некрасивую строку «Привет, » (с висящей "
        "запятой и пробелом).\n\n"
        "Ожидаемое поведение: если передан пустой товар или его наименование пустое, "
        "функция должна возвращать строку «Привет, безымянный товар».\n\n"
        "Критерии приёмки:\n"
        "- Когда я вызываю Приветствие с пустой ссылкой или пустым наименованием, "
        "тогда получаю «Привет, безымянный товар»;\n"
        "- Когда наименование заполнено, тогда поведение не меняется.\n\n"
        "[Демо-задача MVP 1c-vibe: правка BSL]",
    ),
    (
        "Добавить реквизит «Артикул» в справочник Товары",
        "Для складского учёта нужен реквизит «Артикул» (строка длиной 50, "
        "переменная) — только в метаданных, код не трогаем.\n\n"
        "Критерии приёмки:\n"
        "- В Object.xml справочника Товары появляется атрибут «Артикул» "
        "(тип строка, длина 50, переменная);\n"
        "- Существующие атрибуты не изменились;\n"
        "- BSL-модули не затронуты.\n\n"
        "[Демо-задача MVP 1c-vibe: правка метаданных XML]",
    ),
    (
        "Функция расчёта цены с НДС в модуле менеджера",
        "В модуле менеджера справочника Товары уже есть функция СуммаНДС(Сумма, "
        "СтавкаНДС). Нужна парная экспортная функция ЦенаСНДС(Сумма, СтавкаНДС), "
        "возвращающая сумму с учётом НДС, с проверкой отрицательных значений: "
        "при отрицательной сумме или ставке — ВызватьИсключение с понятным текстом.\n\n"
        "Критерии приёмки:\n"
        "- Функция экспортная, есть комментарий в формате // Параметры: ...;\n"
        "- ЦенаСНДС(100, 20) = 120;\n"
        "- При отрицательных параметрах выбрасывается исключение;\n"
        "- Существующая функция СуммаНДС не изменилась.\n\n"
        "[Демо-задача MVP 1c-vibe: новый код + документация]",
    ),
]


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dry = "--dry" in sys.argv[1:]
    if not args:
        print(__doc__)
        sys.exit(2)
    project = args[0]

    for summary, description in DEMO_TASKS:
        if dry:
            print(f"[dry] {project}: {summary}")
            continue
        key = create_issue(project, summary, description, ISSUE_TYPE, labels=["1c-vibe-demo"])
        print(f"Создана задача {key}: {summary}")


if __name__ == "__main__":
    main()
